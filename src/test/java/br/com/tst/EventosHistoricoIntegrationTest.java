/** Eventos de histórico de entrega, substituição, descarte, treinamentos, turmas, presenças e documentos. */
@SpringBootTest(properties = {"spring.datasource.url=jdbc:h2:mem:eventos;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa", "spring.datasource.password=", "spring.jpa.hibernate.ddl-auto=create-drop"})
@AutoConfigureMockMvc
class EventosHistoricoIntegrationTest {
    static final io.zonky.test.db.postgres.embedded.EmbeddedPostgres PG;
    static {
        try { PG = io.zonky.test.db.postgres.embedded.EmbeddedPostgres.start(); } catch (java.io.IOException e) { throw new ExceptionInInitializerError(e); }
    }

    @org.springframework.test.context.DynamicPropertySource
    static void banco(org.springframework.test.context.DynamicPropertyRegistry r) {
        r.add("spring.datasource.url", () -> PG.getJdbcUrl("postgres", "postgres"));
        r.add("spring.datasource.username", () -> "postgres");
        r.add("spring.datasource.password", () -> "postgres");
        r.add("spring.datasource.driver-class-name", () -> "org.postgresql.Driver");
    }

    @Autowired MockMvc mvc;
    @Autowired FuncionarioRepository repository;
    @Autowired PasswordEncoder encoder;
    @Autowired ObjectMapper json;

    @BeforeAll
    static void tabelas(@Autowired JdbcTemplate jdbc) {
        jdbc.execute("create table if not exists historico_alteracoes(id bigint generated by default as identity primary key, autor_id bigint, criado_em timestamp default current_timestamp not null, area_do_site varchar(40) not null, registro_id bigint not null, acao varchar(40) not null, antes jsonb, depois jsonb)");
        jdbc.execute("create table if not exists historico_comentarios(id bigint generated by default as identity primary key, historico_id bigint not null, autor_id bigint, texto varchar(1000) not null, criado_em timestamp default current_timestamp not null)");
        jdbc.execute("create table if not exists entregas_epi(id bigint generated by default as identity primary key, funcionario_id bigint, data_entrega date, criada_em timestamp, responsavel_id bigint)");
        jdbc.execute("create table if not exists entrega_epi_itens(id bigint generated by default as identity primary key, entrega_id bigint, epi_id bigint, encerrado_em timestamp, motivo_encerramento varchar(2100), encerrado_por_id bigint, item_anterior_id bigint)");
        jdbc.execute("create table if not exists fichas_entrega_epi(entrega_id bigint primary key, nome varchar(255), conteudo bytea)");
        jdbc.execute("create table if not exists turmas_treinamento(id bigint generated by default as identity primary key, nr_id int not null, data date not null, horario time not null, documento_nome varchar(255), documento_tipo_conteudo varchar(255), documento_conteudo bytea)");
        jdbc.execute("create table if not exists presencas_treinamento(id bigint generated by default as identity primary key, turma_id bigint not null, funcionario_id bigint not null, presente boolean not null, concluido_em date, vencimento date)");
    }

    String login(String role, String cpf) throws Exception {
        var f = new Funcionario("Teste", "Cargo", cpf, "Setor");
        f.setEmail(cpf + "@marmetalurgia.com");
        f.setPermissoes(role);
        f.setSenhaHash(encoder.encode("Senha-de-teste-123"));
        repository.save(f);
        return json.readTree(mvc.perform(post("/auth/login").contentType("application/json")
                .content(json.writeValueAsString(Map.of("email", cpf, "senha", "Senha-de-teste-123")))).andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString()).get("access_token").asText();
    }

    long idDe(String cpf) {
        return repository.findAll().stream().filter(f -> cpf.equals(f.getCpf())).findFirst().orElseThrow().getId();
    }

    long criarEpi(String token, int ca) throws Exception {
        var body = Map.of("ca", ca, "lote", "L1", "nome", "Luva", "vencimento", "2099-01-01", "substituido", false);
        return json.readTree(mvc.perform(post("/epis").header("Authorization", "Bearer " + token).contentType("application/json")
                .content(json.writeValueAsString(body))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).get("id").asLong();
    }

    JsonNode historico(String token, String area, long registro) throws Exception {
        return json.readTree(mvc.perform(get("/historico?areaDoSite=" + area + "&registroId=" + registro).header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andReturn().getResponse().getContentAsString()).get("itens");
    }

    @Test
    void entregaSubstituicaoEDescarteSaoRegistradas() throws Exception {
        String tst = login("tst", "10000000001");
        long operario = idDe("10000000001");
        long a = criarEpi(tst, 501), b = criarEpi(tst, 502);

        mvc.perform(post("/entregas-epis").header("Authorization", "Bearer " + tst).contentType("application/json")
                .content(json.writeValueAsString(Map.of("funcionarioId", operario, "dataEntrega", "2026-01-10", "epiIds", List.of(a)))))
                .andExpect(status().isCreated());
        mvc.perform(post("/epis/" + a + "/substituicao").header("Authorization", "Bearer " + tst).contentType("application/json")
                .content(json.writeValueAsString(Map.of("novoEpiId", b, "motivo", "Rasgou", "data", "2026-02-01")))).andExpect(status().isOk());
        mvc.perform(post("/epis/" + b + "/descarte").header("Authorization", "Bearer " + tst).contentType("application/json")
                .content(json.writeValueAsString(Map.of("motivo", "Vencido", "data", "2026-03-01")))).andExpect(status().isOk());

        var doA = historico(tst, "EPI", a);
        assertEquals("SUBSTITUICAO", doA.get(0).get("acao").asText());
        assertEquals("Rasgou", doA.get(0).get("depois").get("motivo").asText());
        assertEquals("ENTREGA", doA.get(1).get("acao").asText());
        assertEquals(operario, doA.get(1).get("depois").get("funcionarioId").asLong());

        var doB = historico(tst, "EPI", b);
        assertEquals("DESCARTE", doB.get(0).get("acao").asText());
        assertEquals("Vencido", doB.get(0).get("depois").get("motivo").asText());
        assertEquals("ENTREGA", doB.get(1).get("acao").asText());
        assertEquals(a, doB.get(1).get("depois").get("substituiu").asLong());
        assertEquals(operario, doB.get(0).get("autorId").asLong());
    }

    @Test
    void validadeDaNrCursoTurmaPresencaEDocumentoSaoRegistrados() throws Exception {
        String adm = login("ADM", "10000000002");
        long aluno = idDe("10000000002");
        mvc.perform(post("/nrs").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"id\":777,\"nome\":\"NR 777 - Teste\",\"validadeMeses\":12.5}")).andExpect(status().isCreated())
                .andExpect(jsonPath("$.validadeMeses").value(12.5));

        mvc.perform(put("/nrs/777").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"id\":777,\"nome\":\"NR 777 - Teste\",\"validadeMeses\":24}")).andExpect(status().isOk());
        var nr = historico(adm, "NR", 777);
        assertEquals("EDICAO", nr.get(0).get("acao").asText());
        assertEquals(12.5, nr.get(0).get("antes").get("validadeMeses").asDouble());
        assertEquals(24.0, nr.get(0).get("depois").get("validadeMeses").asDouble());

        long turma = json.readTree(mvc.perform(post("/treinamentos/turmas").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content(json.writeValueAsString(Map.of("nrId", 777, "data", "2026-09-01", "horario", "08:00:00", "funcionarioIds", List.of(aluno)))))
                .andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).get("id").asLong();
        assertEquals("CRIACAO", historico(adm, "TURMA", turma).get(0).get("acao").asText());

        mvc.perform(patch("/treinamentos/turmas/" + turma + "/participantes/" + aluno).header("Authorization", "Bearer " + adm)
                .contentType("application/json").content("{\"presente\":true}")).andExpect(status().isOk());
        var presenca = historico(adm, "TURMA", turma).get(0);
        assertEquals("PRESENCA", presenca.get("acao").asText());
        assertEquals(aluno, presenca.get("depois").get("funcionarioId").asLong());
        assertEquals(true, presenca.get("depois").get("presente").asBoolean());

        var pdf = new MockMultipartFile("arquivo", "lista.pdf", "application/pdf", "%PDF-1.4 exemplo".getBytes());
        mvc.perform(multipart("/treinamentos/turmas/" + turma + "/documento").file(pdf).with(r -> { r.setMethod("PUT"); return r; })
                .header("Authorization", "Bearer " + adm)).andExpect(status().isOk());
        var novo = new MockMultipartFile("arquivo", "lista-v2.pdf", "application/pdf", "%PDF-1.4 exemplo v2".getBytes());
        mvc.perform(multipart("/treinamentos/turmas/" + turma + "/documento").file(novo).with(r -> { r.setMethod("PUT"); return r; })
                .header("Authorization", "Bearer " + adm)).andExpect(status().isOk());
        mvc.perform(get("/treinamentos/turmas/" + turma + "/documento").header("Authorization", "Bearer " + adm))
                .andExpect(status().isOk()).andExpect(content().bytes("%PDF-1.4 exemplo v2".getBytes()));
        mvc.perform(multipart("/treinamentos/turmas/" + turma + "/documento")
                .file(new MockMultipartFile("arquivo", "x.exe", "application/octet-stream", "MZ".getBytes()))
                .with(r -> { r.setMethod("PUT"); return r; }).header("Authorization", "Bearer " + adm)).andExpect(status().isConflict());
        mvc.perform(delete("/treinamentos/turmas/" + turma + "/documento").header("Authorization", "Bearer " + adm)).andExpect(status().isNoContent());
        mvc.perform(get("/treinamentos/turmas/" + turma + "/documento").header("Authorization", "Bearer " + adm)).andExpect(status().isNotFound());

        var eventos = historico(adm, "TURMA", turma);
        assertEquals("DOCUMENTO_EXCLUSAO", eventos.get(0).get("acao").asText());
        assertEquals("lista-v2.pdf", eventos.get(0).get("antes").get("documentoNome").asText());
        assertEquals("DOCUMENTO_ALTERACAO", eventos.get(1).get("acao").asText());
        assertEquals("lista.pdf", eventos.get(1).get("antes").get("documentoNome").asText());
        assertEquals("DOCUMENTO_ENVIO", eventos.get(2).get("acao").asText());
    }

    @Test
    void retornoAoStatusAtivoRegistraObservacoes() throws Exception {
        String adm = login("ADM", "10000000004");
        long id = idDe("10000000004");
        for (var status : List.of("Af", "At")) {
            mvc.perform(patch("/funcionarios/" + id).header("Authorization", "Bearer " + adm).contentType("application/json")
                    .content("{\"status\":\"" + status + "\"}")).andExpect(status().isOk());
        }
        var eventos = historico(adm, "FUNCIONARIO", id);
        assertEquals("REATIVACAO", eventos.get(0).get("acao").asText());
        assertEquals(3, eventos.get(0).get("depois").get("observacoes").size());
        assertEquals("MUDANCA_STATUS", eventos.get(1).get("acao").asText());
    }

    @Test
    void filtroPorDataEPaginacao() throws Exception {
        String adm = login("ADM", "10000000003");
        for (int i = 0; i < 3; i++) {
            mvc.perform(post("/nrs").header("Authorization", "Bearer " + adm).contentType("application/json")
                    .content("{\"id\":" + (880 + i) + ",\"nome\":\"NR pag " + i + "\"}")).andExpect(status().isCreated());
        }
        mvc.perform(get("/historico?areaDoSite=NR&tamanho=2&pagina=1").header("Authorization", "Bearer " + adm))
                .andExpect(jsonPath("$.itens.length()").value(org.hamcrest.Matchers.lessThanOrEqualTo(2)))
                .andExpect(jsonPath("$.pagina").value(1)).andExpect(jsonPath("$.tamanho").value(2));
        mvc.perform(get("/historico?areaDoSite=NR&registroId=880&de=2000-01-01&ate=2000-01-02").header("Authorization", "Bearer " + adm))
                .andExpect(jsonPath("$.total").value(0));
        mvc.perform(get("/historico?areaDoSite=NR&registroId=880&de=2000-01-01").header("Authorization", "Bearer " + adm))
                .andExpect(jsonPath("$.total").value(1));
    }
}
