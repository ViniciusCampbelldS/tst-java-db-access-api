package br.com.tst;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

import br.com.tst.model.Funcionario;
import br.com.tst.repository.FuncionarioRepository;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.Map;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest(properties = {"spring.datasource.url=jdbc:h2:mem:hist;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa", "spring.datasource.password=", "spring.jpa.hibernate.ddl-auto=create-drop"})
@AutoConfigureMockMvc
class HistoricoIntegrationTest {
    @Autowired MockMvc mvc;
    @Autowired FuncionarioRepository repository;
    @Autowired PasswordEncoder encoder;
    @Autowired ObjectMapper json;
    @Autowired JdbcTemplate jdbc;

    @BeforeAll
    static void tabelas(@Autowired JdbcTemplate jdbc) {
        jdbc.execute("create table if not exists historico_alteracoes(id bigint generated by default as identity primary key, autor_id bigint, criado_em timestamp default current_timestamp not null, area_do_site varchar(40) not null, registro_id bigint not null, acao varchar(40) not null, antes jsonb, depois jsonb)");
        jdbc.execute("create table if not exists entregas_epi(id bigint primary key, funcionario_id bigint)");
        jdbc.execute("create table if not exists entrega_epi_itens(id bigint primary key, entrega_id bigint, epi_id bigint, encerrado_em timestamp)");
    }

    String login(String role, String cpf) throws Exception {
        var f = new Funcionario("Teste", "Cargo", cpf, "Setor");
        f.setEmail(cpf + "@marmetalurgia.com");
        f.setPermissoes(role);
        f.setSenhaHash(encoder.encode("Senha-de-teste-123"));
        repository.save(f);
        return json.readTree(mvc.perform(post("/auth/login").contentType("application/json")
                .content(json.writeValueAsString(Map.of("email", cpf, "senha", "Senha-de-teste-123")))).andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString()).get("access_token").asText();
    }

    @Test
    void edicoesDeEpiGeramHistoricoComAutorDaSessao() throws Exception {
        String tst = login("tst", "33333333333");
        long autor = repository.findAll().stream().filter(f -> "33333333333".equals(f.getCpf())).findFirst().orElseThrow().getId();
        var body = Map.of("ca", 123, "lote", "L1", "nome", "Luva", "vencimento", "2099-01-01", "substituido", false);
        long id = json.readTree(mvc.perform(post("/epis").header("Authorization", "Bearer " + tst).contentType("application/json")
                .content(json.writeValueAsString(body))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).get("id").asLong();
        mvc.perform(patch("/epis/" + id).header("Authorization", "Bearer " + tst).contentType("application/json")
                .content("{\"nome\":\"Luva nitrílica\"}")).andExpect(status().isOk());
        mvc.perform(patch("/epis/" + id).header("Authorization", "Bearer " + tst).contentType("application/json")
                .content("{\"nome\":\"Luva nitrílica\"}")).andExpect(status().isOk());

        mvc.perform(get("/historico?areaDoSite=EPI&registroId=" + id).header("Authorization", "Bearer " + tst))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.total").value(2))
                .andExpect(jsonPath("$.itens[0].acao").value("EDICAO"))
                .andExpect(jsonPath("$.itens[0].autorId").value(autor))
                .andExpect(jsonPath("$.itens[0].antes.nome").value("Luva"))
                .andExpect(jsonPath("$.itens[0].depois.nome").value("Luva nitrílica"))
                .andExpect(jsonPath("$.itens[0].depois.ca").doesNotExist())
                .andExpect(jsonPath("$.itens[1].acao").value("CRIACAO"));
    }

    @Test
    void operarioNaoLeHistorico() throws Exception {
        String operario = login("field", "44444444444");
        mvc.perform(get("/historico").header("Authorization", "Bearer " + operario)).andExpect(status().isForbidden());
    }
}
