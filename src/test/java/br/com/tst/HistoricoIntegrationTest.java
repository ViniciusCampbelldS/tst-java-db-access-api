package br.com.tst;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

import br.com.tst.model.Funcionario;
import br.com.tst.repository.FuncionarioRepository;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.Map;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest(properties = {"spring.datasource.url=jdbc:h2:mem:hist;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa", "spring.datasource.password=", "spring.jpa.hibernate.ddl-auto=create-drop"})
@AutoConfigureMockMvc
class HistoricoIntegrationTest {
    @Autowired MockMvc mvc;
    @Autowired FuncionarioRepository repository;
    @Autowired PasswordEncoder encoder;
    @Autowired ObjectMapper json;
    @Autowired JdbcTemplate jdbc;

    @BeforeAll
    static void tabelas(@Autowired JdbcTemplate jdbc) {
        jdbc.execute("create table if not exists historico_alteracoes(id bigint generated by default as identity primary key, autor_id bigint, criado_em timestamp default current_timestamp not null, area_do_site varchar(40) not null, registro_id bigint not null, acao varchar(40) not null, antes jsonb, depois jsonb, lote_operacao_id uuid)");
        jdbc.execute("create table if not exists historico_comentarios(id bigint generated by default as identity primary key, historico_id bigint not null, autor_id bigint, texto varchar(1000) not null)");
        jdbc.execute("create table if not exists entregas_epi(id bigint primary key, funcionario_id bigint)");
        jdbc.execute("create table if not exists entrega_epi_itens(id bigint primary key, entrega_id bigint, epi_id bigint, encerrado_em timestamp)");
    }

    String login(String role, String cpf) throws Exception {
        var f = new Funcionario("Teste", "Cargo", cpf, "Setor");
        f.setEmail(cpf + "@marmetalurgia.com");
        f.setPermissoes(role);
        f.setSenhaHash(encoder.encode("Senha-de-teste-123"));
        repository.save(f);
        return json.readTree(mvc.perform(post("/auth/login").contentType("application/json")
                .content(json.writeValueAsString(Map.of("email", cpf, "senha", "Senha-de-teste-123")))).andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString()).get("access_token").asText();
    }

    @Test
    void edicoesDeEpiGeramHistoricoComAutorDaSessao() throws Exception {
        String tst = login("tst", "33333333333");
        long autor = repository.findAll().stream().filter(f -> "33333333333".equals(f.getCpf())).findFirst().orElseThrow().getId();
        var body = Map.of("ca", 123, "lote", "L1", "nome", "Luva", "vencimento", "2099-01-01", "substituido", false);
        long id = json.readTree(mvc.perform(post("/epis").header("Authorization", "Bearer " + tst).contentType("application/json")
                .content(json.writeValueAsString(body))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).get("id").asLong();
        mvc.perform(patch("/epis/" + id).header("Authorization", "Bearer " + tst).contentType("application/json")
                .content("{\"nome\":\"Luva nitrílica\"}")).andExpect(status().isOk());
        mvc.perform(patch("/epis/" + id).header("Authorization", "Bearer " + tst).contentType("application/json")
                .content("{\"nome\":\"Luva nitrílica\"}")).andExpect(status().isOk());

        mvc.perform(get("/historico?areaDoSite=EPI&registroId=" + id).header("Authorization", "Bearer " + tst))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.total").value(2))
                .andExpect(jsonPath("$.itens[0].acao").value("EDICAO"))
                .andExpect(jsonPath("$.itens[0].autorId").value(autor))
                .andExpect(jsonPath("$.itens[0].antes.nome").value("Luva"))
                .andExpect(jsonPath("$.itens[0].depois.nome").value("Luva nitrílica"))
                .andExpect(jsonPath("$.itens[0].depois.ca").doesNotExist())
                .andExpect(jsonPath("$.itens[1].acao").value("CRIACAO"));
    }

    @Test
    void operarioNaoLeHistorico() throws Exception {
        String operario = login("field", "44444444444");
        mvc.perform(get("/historico").header("Authorization", "Bearer " + operario)).andExpect(status().isForbidden());
    }

    @Test
    void criacaoEmLoteApareceAgrupadaMasFicaIndividualNoBanco() throws Exception {
        String tst = login("tst", "55555555555");
        var epi = Map.of("ca", 321, "lote", "L9", "nome", "Capacete", "vencimento", "2099-01-01", "substituido", false);
        mvc.perform(post("/epis/bulk").header("Authorization", "Bearer " + tst).contentType("application/json")
                .content(json.writeValueAsString(Map.of("epis", java.util.List.of(epi, epi, epi))))).andExpect(status().isCreated());

        mvc.perform(get("/historico?areaDoSite=EPI&agrupar=true&tamanho=1").header("Authorization", "Bearer " + tst))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.itens[0].acao").value("CRIACAO"))
                .andExpect(jsonPath("$.itens[0].quantidade").value(3))
                .andExpect(jsonPath("$.itens[0].detalhes.length()").value(3))
                .andExpect(jsonPath("$.itens[0].detalhes[0].depois.nome").value("Capacete"));
        mvc.perform(get("/historico?areaDoSite=EPI&tamanho=3").header("Authorization", "Bearer " + tst))
                .andExpect(jsonPath("$.itens.length()").value(3))
                .andExpect(jsonPath("$.itens[0].quantidade").value(1));
    }

    @Test
    void comentariosSaoSomenteDeAcrescimo() throws Exception {
        String adm = login("ADM", "66666666666");
        mvc.perform(post("/nrs").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"id\":901,\"nome\":\"NR 901 - Teste\"}")).andExpect(status().isCreated());
        var lista = json.readTree(mvc.perform(get("/historico?areaDoSite=NR&registroId=901").header("Authorization", "Bearer " + adm))
                .andReturn().getResponse().getContentAsString());
        long evento = lista.get("itens").get(0).get("id").asLong();
        org.junit.jupiter.api.Assertions.assertEquals("CRIACAO", lista.get("itens").get(0).get("acao").asText());

        mvc.perform(post("/historico/" + evento + "/comentarios").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"texto\":\"Primeira nota\"}")).andExpect(status().isOk()).andExpect(jsonPath("$[0]").value("Primeira nota"));
        mvc.perform(post("/historico/" + evento + "/comentarios").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"texto\":\"Segunda nota\"}")).andExpect(jsonPath("$.length()").value(2));
        mvc.perform(post("/historico/" + evento + "/comentarios").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"texto\":\"  \"}")).andExpect(status().isBadRequest());
        mvc.perform(get("/historico?areaDoSite=NR&registroId=901").header("Authorization", "Bearer " + adm))
                .andExpect(jsonPath("$.itens[0].comentarios[1]").value("Segunda nota"));
        mvc.perform(put("/historico/" + evento + "/comentarios").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"texto\":\"x\"}")).andExpect(status().is4xxClientError());
    }

    @Test
    void exclusoesSaoRegistradasEFuncionarioApenasInativa() throws Exception {
        String adm = login("ADM", "77777777777");
        mvc.perform(post("/nrs").header("Authorization", "Bearer " + adm).contentType("application/json")
                .content("{\"id\":902,\"nome\":\"NR 902 - Teste\"}")).andExpect(status().isCreated());
        mvc.perform(delete("/nrs/902").header("Authorization", "Bearer " + adm)).andExpect(status().isNoContent());
        mvc.perform(get("/historico?areaDoSite=NR&registroId=902").header("Authorization", "Bearer " + adm))
                .andExpect(jsonPath("$.itens[0].acao").value("EXCLUSAO"))
                .andExpect(jsonPath("$.itens[0].antes.nome").value("NR 902 - Teste"));

        login("field", "88888888888");
        long id = repository.findAll().stream().filter(f -> "88888888888".equals(f.getCpf())).findFirst().orElseThrow().getId();
        mvc.perform(delete("/funcionarios/" + id).header("Authorization", "Bearer " + adm)).andExpect(status().isNoContent());
        org.junit.jupiter.api.Assertions.assertEquals("In", repository.findById(id).orElseThrow().getStatus());
        mvc.perform(get("/historico?areaDoSite=FUNCIONARIO&registroId=" + id).header("Authorization", "Bearer " + adm))
                .andExpect(jsonPath("$.itens[0].acao").value("INATIVACAO"))
                .andExpect(jsonPath("$.itens[0].depois.status").value("In"));
    }}
