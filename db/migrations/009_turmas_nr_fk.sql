-- Requer a migração 004. A NR da turma passa a ser uma FK inteira para nrs(id), consistente com o curso.
BEGIN;

-- Em bases antigas "treinamentos" era uma tabela vazia de outro formato (sem nr_id); recria no formato do catálogo.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = 'treinamentos' AND column_name = 'nr_id') THEN
        IF EXISTS (SELECT 1 FROM public.treinamentos) THEN
            RAISE EXCEPTION 'treinamentos legado possui registros; migre-os antes de aplicar.';
        END IF;
        DROP TABLE public.treinamentos CASCADE;
        CREATE TABLE public.treinamentos (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nr_id bigint NOT NULL REFERENCES public.nrs(id),
            nome varchar(250) NOT NULL,
            validade_meses integer NOT NULL CHECK (validade_meses > 0)
        );
        ALTER TABLE public.treinamentos ENABLE ROW LEVEL SECURITY;
        REVOKE ALL ON public.treinamentos FROM PUBLIC;
        ALTER TABLE public.turmas_treinamento
            ADD CONSTRAINT fk_turmas_treinamento_curso FOREIGN KEY (treinamento_id) REFERENCES public.treinamentos(id);
    END IF;
END $$;

-- Turmas legadas ganham um curso no catálogo (NR + nome), com validade estimada pelo intervalo data -> vencimento.
INSERT INTO public.treinamentos (nr_id, nome, validade_meses)
SELECT n.id, t.nome,
       GREATEST(1, MIN((extract(year FROM age(t.vencimento, t.data)) * 12 + extract(month FROM age(t.vencimento, t.data)))::int))
FROM public.turmas_treinamento t
JOIN public.nrs n ON n.id = substring(t.nr FROM '[0-9]+')::bigint
WHERE t.treinamento_id IS NULL
  AND NOT EXISTS (SELECT 1 FROM public.treinamentos c WHERE c.nr_id = n.id AND c.nome = t.nome)
GROUP BY n.id, t.nome;

UPDATE public.turmas_treinamento t
SET treinamento_id = c.id
FROM public.treinamentos c
WHERE t.treinamento_id IS NULL AND c.nome = t.nome AND c.nr_id = substring(t.nr FROM '[0-9]+')::bigint;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.turmas_treinamento WHERE treinamento_id IS NULL) THEN
        RAISE EXCEPTION 'Existem turmas sem curso correspondente; revise-as antes de aplicar.';
    END IF;
END $$;

-- O vencimento deixa de ser da turma e passa a ser de cada participante aprovado.
UPDATE public.presencas_treinamento p
SET concluido_em = t.data, vencimento = t.vencimento
FROM public.turmas_treinamento t
WHERE p.turma_id = t.id AND p.presente AND p.concluido_em IS NULL;

UPDATE public.turmas_treinamento SET horario = TIME '00:00' WHERE horario IS NULL;

ALTER TABLE public.turmas_treinamento
    ADD COLUMN IF NOT EXISTS nr_id integer;
UPDATE public.turmas_treinamento t SET nr_id = c.nr_id FROM public.treinamentos c WHERE c.id = t.treinamento_id;

ALTER TABLE public.turmas_treinamento
    ALTER COLUMN nr_id SET NOT NULL,
    ALTER COLUMN treinamento_id SET NOT NULL,
    ALTER COLUMN horario SET NOT NULL,
    ADD CONSTRAINT fk_turmas_nr FOREIGN KEY (nr_id) REFERENCES public.nrs(id),
    DROP COLUMN nr,
    DROP COLUMN vencimento;

-- Garante que a NR da turma é sempre a NR do curso escolhido.
ALTER TABLE public.treinamentos ADD CONSTRAINT uk_treinamentos_id_nr UNIQUE (id, nr_id);
ALTER TABLE public.turmas_treinamento
    ADD CONSTRAINT fk_turmas_curso_nr FOREIGN KEY (treinamento_id, nr_id) REFERENCES public.treinamentos(id, nr_id);

COMMIT;
