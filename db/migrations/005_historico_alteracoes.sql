BEGIN;

CREATE TABLE IF NOT EXISTS public.historico_alteracoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id bigint REFERENCES public.funcionarios(id) ON DELETE SET NULL,
    criado_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    entidade varchar(40) NOT NULL,
    registro_id bigint NOT NULL,
    acao varchar(40) NOT NULL,
    antes jsonb,
    depois jsonb
);

CREATE INDEX IF NOT EXISTS idx_historico_entidade_registro
    ON public.historico_alteracoes (entidade, registro_id, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_historico_criado_em
    ON public.historico_alteracoes (criado_em DESC);

-- O histórico é somente de acréscimo: UPDATE e DELETE são bloqueados.
-- A única exceção é o SET NULL de autor_id quando um funcionário é removido.
CREATE OR REPLACE FUNCTION public.historico_alteracoes_imutavel() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.autor_id IS NULL AND OLD.autor_id IS NOT NULL
       AND (NEW.id, NEW.criado_em, NEW.entidade, NEW.registro_id, NEW.acao, NEW.antes, NEW.depois)
           IS NOT DISTINCT FROM (OLD.id, OLD.criado_em, OLD.entidade, OLD.registro_id, OLD.acao, OLD.antes, OLD.depois) THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'historico_alteracoes é somente de acréscimo';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_historico_alteracoes_imutavel ON public.historico_alteracoes;
CREATE TRIGGER trg_historico_alteracoes_imutavel
    BEFORE UPDATE OR DELETE ON public.historico_alteracoes
    FOR EACH ROW EXECUTE FUNCTION public.historico_alteracoes_imutavel();

COMMIT;
