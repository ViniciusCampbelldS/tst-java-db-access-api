BEGIN;

CREATE TABLE IF NOT EXISTS public.treinamentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nr_id bigint NOT NULL REFERENCES public.nrs(id),
    nome varchar(250) NOT NULL,
    validade_meses integer NOT NULL CHECK (validade_meses > 0)
);

-- Preserva as turmas antigas e adiciona a referência ao catálogo normalizado.
ALTER TABLE public.turmas_treinamento
    ADD COLUMN IF NOT EXISTS treinamento_id bigint REFERENCES public.treinamentos(id),
    ADD COLUMN IF NOT EXISTS horario time,
    ADD COLUMN IF NOT EXISTS documento_nome varchar(255),
    ADD COLUMN IF NOT EXISTS criada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE public.presencas_treinamento
    ADD COLUMN IF NOT EXISTS concluido_em date,
    ADD COLUMN IF NOT EXISTS vencimento date;

DO $$
BEGIN
    IF (SELECT is_identity = 'NO' FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'turmas_treinamento' AND column_name = 'id') THEN
        ALTER TABLE public.turmas_treinamento ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF (SELECT is_identity = 'NO' FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'presencas_treinamento' AND column_name = 'id') THEN
        ALTER TABLE public.presencas_treinamento ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uk_presencas_turma_funcionario
    ON public.presencas_treinamento(turma_id, funcionario_id);

ALTER TABLE public.treinamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.turmas_treinamento ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.presencas_treinamento ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.treinamentos, public.turmas_treinamento, public.presencas_treinamento FROM PUBLIC;

DO $$
DECLARE papel text;
BEGIN
  FOREACH papel IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=papel) THEN
      EXECUTE format('REVOKE ALL ON public.treinamentos, public.turmas_treinamento, public.presencas_treinamento FROM %I',papel);
    END IF;
  END LOOP;
END $$;

COMMIT;
