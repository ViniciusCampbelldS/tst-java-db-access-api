BEGIN;

-- Eventos da mesma operação em lote (ex.: criação de vários EPIs) compartilham o mesmo identificador;
-- cada objeto continua com seu próprio evento.
ALTER TABLE public.historico_alteracoes ADD COLUMN IF NOT EXISTS lote_operacao_id uuid;
CREATE INDEX IF NOT EXISTS idx_historico_lote_operacao
    ON public.historico_alteracoes (lote_operacao_id) WHERE lote_operacao_id IS NOT NULL;

-- Notas livres anexadas a um evento do histórico: somente acréscimo, sem data.
CREATE TABLE IF NOT EXISTS public.historico_comentarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    historico_id bigint NOT NULL REFERENCES public.historico_alteracoes(id) ON DELETE RESTRICT,
    autor_id bigint REFERENCES public.funcionarios(id) ON DELETE RESTRICT,
    texto text NOT NULL CHECK (length(btrim(texto)) > 0 AND length(texto) <= 1000)
);
CREATE INDEX IF NOT EXISTS idx_historico_comentarios_evento
    ON public.historico_comentarios (historico_id, id);

DROP TRIGGER IF EXISTS trg_historico_comentarios_imutavel ON public.historico_comentarios;
CREATE TRIGGER trg_historico_comentarios_imutavel
    BEFORE UPDATE OR DELETE ON public.historico_comentarios
    FOR EACH ROW EXECUTE FUNCTION public.historico_alteracoes_imutavel();

ALTER TABLE public.historico_alteracoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historico_comentarios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.historico_alteracoes, public.historico_comentarios FROM PUBLIC;

DO $$
DECLARE papel text;
BEGIN
  FOREACH papel IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=papel) THEN
      EXECUTE format('REVOKE ALL ON public.historico_alteracoes, public.historico_comentarios FROM %I',papel);
    END IF;
  END LOOP;
END $$;

COMMIT;
