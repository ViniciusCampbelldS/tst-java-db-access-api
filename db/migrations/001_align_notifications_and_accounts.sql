-- Execute once during coordinated backend/frontend release. Existing rules are preserved.
BEGIN;
LOCK TABLE nrs,funcionarios_nrs,epis,funcionarios IN SHARE ROW EXCLUSIVE MODE;
-- Preserve the test NR and its references, using its actual number (00).
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM nrs WHERE id=40 AND nome ~ '^NR 00') THEN
  IF EXISTS(SELECT 1 FROM nrs WHERE id=0) THEN RAISE EXCEPTION 'NR zero already exists; reconcile before migration'; END IF;
  UPDATE nrs SET id=0 WHERE id=40 AND nome ~ '^NR 00';
 END IF;
END $$;
ALTER TABLE nrs ALTER COLUMN id DROP IDENTITY IF EXISTS;
ALTER TABLE nrs ADD CONSTRAINT ck_nr_number CHECK(id BETWEEN 0 AND 2147483647);
ALTER TABLE funcionarios_nrs ALTER COLUMN nr_id SET NOT NULL;
ALTER TABLE funcionarios_nrs ADD CONSTRAINT uk_funcionario_nr UNIQUE(funcionario_id,nr_id);
ALTER TABLE epis ALTER COLUMN ca TYPE integer USING trim(ca)::integer;
ALTER TABLE epis ALTER COLUMN ca SET NOT NULL;
ALTER TABLE epis ADD CONSTRAINT ck_epi_ca CHECK(ca>0);
CREATE TABLE dias_notificacao_epis(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ca integer NOT NULL UNIQUE CHECK(ca>0),dias_aviso integer NOT NULL CHECK(dias_aviso>0));
CREATE TABLE dias_notificacao_treinamentos(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nr integer NOT NULL UNIQUE REFERENCES nrs(id) ON UPDATE CASCADE,dias_aviso integer NOT NULL CHECK(dias_aviso>0));
-- Gather both legacy sources; fail instead of silently choosing conflicting rules.
CREATE TEMP TABLE regras_migracao ON COMMIT DROP AS
 SELECT ca_ou_nr,is_norma,dias_aviso FROM dias_notificacao_epi
 UNION ALL SELECT ca_ou_nr,is_norma,dias_aviso FROM dias_notificacao;
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM regras_migracao WHERE dias_aviso<=0 OR dias_aviso IS NULL) THEN RAISE EXCEPTION 'Invalid warning days'; END IF;
 IF EXISTS(SELECT 1 FROM regras_migracao WHERE (NOT is_norma AND trim(ca_ou_nr)!~'^[0-9]+$') OR (is_norma AND trim(ca_ou_nr)!~'^(NR[- ]*)?[0-9]+$')) THEN RAISE EXCEPTION 'Unrecognized CA/NR';END IF;
 IF EXISTS(SELECT 1 FROM regras_migracao GROUP BY is_norma,regexp_replace(ca_ou_nr,'[^0-9]','','g')::integer HAVING count(DISTINCT dias_aviso)>1) THEN RAISE EXCEPTION 'Conflicting warning rules'; END IF;
END $$;
INSERT INTO dias_notificacao_epis(ca,dias_aviso) SELECT DISTINCT trim(ca_ou_nr)::integer,dias_aviso FROM regras_migracao WHERE NOT is_norma;
INSERT INTO dias_notificacao_treinamentos(nr,dias_aviso) SELECT DISTINCT regexp_replace(ca_ou_nr,'[^0-9]','','g')::integer,dias_aviso FROM regras_migracao WHERE is_norma;
-- Old tables are intentionally retained as a legacy backup; new application never writes them.
ALTER TABLE funcionarios ADD COLUMN versao bigint NOT NULL DEFAULT 0;
ALTER TABLE funcionarios ADD COLUMN email varchar(254),ADD COLUMN senha_hash varchar(255),ADD COLUMN recuperacao_token_hash varchar(64),ADD COLUMN recuperacao_expira_em timestamptz,ADD COLUMN sessao_token_hash varchar(64),ADD COLUMN sessao_expira_em timestamptz;
UPDATE funcionarios SET email='funcionario.'||id||'@marmetalurgia.com';
CREATE UNIQUE INDEX uk_funcionario_email ON funcionarios(lower(email));
CREATE UNIQUE INDEX uk_funcionario_cpf ON funcionarios(cpf);
CREATE UNIQUE INDEX uk_funcionario_reset_token ON funcionarios(recuperacao_token_hash) WHERE recuperacao_token_hash IS NOT NULL;
CREATE UNIQUE INDEX uk_funcionario_session ON funcionarios(sessao_token_hash) WHERE sessao_token_hash IS NOT NULL;
ALTER TABLE funcionarios DROP CONSTRAINT IF EXISTS funcionarios_check;
ALTER TABLE funcionarios ADD CONSTRAINT funcionarios_check CHECK(status IN('At','Af','In') AND permissoes IN('ADM','field','tst','rh','gerencia'));
-- All data goes through the Java API. Do not expose credentials via Supabase REST.
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['funcionarios','funcionarios_nrs','epis','nrs','dias_notificacao_epis','dias_notificacao_treinamentos','dias_notificacao','dias_notificacao_epi','epi_funcionarios','entregas_epi','entregas_epis','entrega_epi_itens','relatos_epi','treinamentos','turmas_treinamento','presencas_treinamento'] LOOP
  IF to_regclass('public.'||t) IS NOT NULL THEN
   EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
   IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='anon') THEN EXECUTE format('REVOKE ALL ON public.%I FROM anon',t);END IF;
   IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN EXECUTE format('REVOKE ALL ON public.%I FROM authenticated',t);END IF;
  END IF;
 END LOOP;
END $$;
COMMIT;
